#!/usr/bin/env python3
"""Write the two compact LaTeX tables of the article from the CSV files of simulate.py.

    table_data.tex  Table 1 (tab:data): corpus, acts, chunks, benchmark questions
    table_main.tex  Table 2 (tab:main): main results, point values, bold best value per
                    panel column, dagger = Holm-significant difference from the panel's
                    reference configuration (taken from tests_all.csv)

All simulated values are EXPECTED values from a seeded simulation (not measured).

Usage (from the repository root, after the simulation):
    python src/make_compact_tables.py          # reads outputs/data, writes outputs/tables
"""
import argparse
from pathlib import Path

import pandas as pd

NOTE = "Expected values from a seeded simulation (not measured)."
RET_METRICS = ["R5", "R10", "MRR", "P1", "nDCG10"]
GEN_METRICS = ["em", "f1", "cit", "sup", "hal", "cor"]
MODELS = ["gpt", "kaz", "llama", "qwen"]
MODEL_NAMES = {"gpt": "GPT-6.1", "kaz": "KazLLM-1.0-8B", "llama": "Llama-3.1-8B", "qwen": "Qwen3.5-9B"}
PANEL_A = [("sentence", "Sentence-level"), ("fixed", "Fixed-size (200 words)"),
           ("sliding", "Sliding window (200/100)"), ("sa", "Structure-aware")]
PANEL_B = [("tfidf", "TF-IDF"), ("bm25", "BM25"), ("labse", "LaBSE"), ("e5", "multilingual-E5-large"),
           ("bge", "BGE-M3"), ("lin", r"Hybrid, linear ($\alpha=0.4$)"), ("rrf", r"Hybrid, RRF ($k=60$)"),
           ("rr", "Hybrid, linear + reranker")]
# comparison in tests_all.csv -> configuration that carries the dagger
DAGGER_A = {"SA - Sentence": "sentence", "SA - Fixed": "fixed", "SA - Sliding": "sliding"}
DAGGER_B = {"Hybrid linear - BM25": "bm25", "Hybrid linear - BGE-M3": "bge",
            "RRF - linear": "rrf", "Reranker - none": "rr"}


def f1d(x):
    s = f"{x:.1f}"
    return "0.0" if s == "-0.0" else s


def num(x):
    return f"{int(round(x)):,}".replace(",", "{,}")


def daggers(tests):
    """Set of (config, metric) whose difference from the panel reference is significant."""
    out = set()
    for _, r in tests[tests["significant"]].iterrows():
        if r["family"] == "F1" and r["comparison"] in DAGGER_A:
            out.add((DAGGER_A[r["comparison"]], r["metric"]))
        elif r["family"] in ("F2", "F2s") and r["comparison"] in DAGGER_B:
            out.add((DAGGER_B[r["comparison"]], r["metric"]))
        elif r["family"] == "F3":
            m = [k for k, v in MODEL_NAMES.items() if r["comparison"].startswith(v + ":")][0]
            out.add((f"{m}_rag", r["metric"]))
    return out


def best(values, lower):
    vals = [round(v, 1) for v in values]
    return min(vals) if lower else max(vals)


def write_main(t2, tests, run_sd, path):
    dag = daggers(tests)

    def val(panel, c, m):
        return float(t2[(t2["panel"] == panel) & (t2["config"] == c) & (t2["metric"] == m)]["value"].iloc[0])

    def cell(v, is_best, is_sig, integer=False):
        s = f"{int(round(v))}" if integer else f1d(v)
        s = r"\textbf{" + s + "}" if is_best else s
        return s + (r"\s" if is_sig else "")

    L = ["% Table 2 (tab:main). Generated by src/make_compact_tables.py from outputs/data/table2_main.csv",
         "% and outputs/data/tests_all.csv. " + NOTE,
         r"\begin{table}[tb]",
         r"\caption{Main results on the test set. Metrics in \%, MRR and nDCG@10 $\times 100$, latency (Lat.) in ms "
         r"per query. Bold: best value in a panel column (lowest for hallucination and latency). $^{\dagger}$: "
         r"significant difference from the panel's reference configuration (Holm-adjusted $p<0.05$): structure-aware "
         r"chunking in Panel~A, the linear hybrid in Panel~B and the same model without retrieval (LLM-only) in "
         r"Panel~C. $n=381$ (A, B) and 400 (C). " + NOTE + r"}\label{tab:main}",
         r"\footnotesize", r"\setlength{\tabcolsep}{4pt}", r"\newcommand{\s}{$^{\dagger}$}",
         r"\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}llrrrrrr@{}}", r"\toprule"]
    for panel, rows, title in (
            ("A", PANEL_A, r"Panel A: chunking (hybrid, $\alpha=0.5$, no reranker); reference: structure-aware"),
            ("B", PANEL_B, r"Panel B: retrievers (structure-aware chunks); reference: linear hybrid")):
        L += [r"\multicolumn{8}{@{}l}{\textit{" + title + r"}}\\",
              r"\multicolumn{2}{@{}l}{Configuration} & R@5 & R@10 & MRR & P@1 & nDCG@10 & Lat.\\", r"\midrule"]
        cfgs = [c for c, _ in rows]
        b = {m: best([val(panel, c, m) for c in cfgs], False) for m in RET_METRICS}
        b["lat"] = min(round(val(panel, c, "latency_ms")) for c in cfgs)
        for c, name in rows:
            cells = [cell(val(panel, c, m), round(val(panel, c, m), 1) == b[m], (c, m) in dag) for m in RET_METRICS]
            lat = val(panel, c, "latency_ms")
            cells.append(cell(lat, round(lat) == b["lat"], False, integer=True))
            L.append(r"\multicolumn{2}{@{}l}{" + name + "} & " + " & ".join(cells) + r"\\")
        L.append(r"\midrule")
    L += [r"\multicolumn{8}{@{}l}{\textit{Panel C: generators (Kazakh system prompt); reference: same model, LLM-only}}\\",
          r"Model & Setting & EM & F1 & Cit.\ acc. & Support & Halluc. & Legal corr.\\", r"\midrule"]
    cfgs = [f"{m}_{s}" for m in MODELS for s in ("llm", "rag")]
    b = {m: best([val("C", c, m) for c in cfgs], m == "hal") for m in GEN_METRICS}
    for m in MODELS:
        for s, sname in (("llm", "LLM-only"), ("rag", "RAG")):
            c = f"{m}_{s}"
            cells = [cell(val("C", c, x), round(val("C", c, x), 1) == b[x], (c, x) in dag) for x in GEN_METRICS]
            L.append((MODEL_NAMES[m] if s == "llm" else "") + f" & {sname} & " + " & ".join(cells) + r"\\")
    sd = run_sd.drop_duplicates("model").set_index("model")["sd_pp"]
    sd_txt = ", ".join(f"{MODEL_NAMES[m]} {f1d(sd[MODEL_NAMES[m]])}" for m in MODELS)
    L += [r"\botrule", r"\end{tabular*}",
          r"\footnotetext{Only the planned comparisons are tested: R@10, MRR and nDCG@10 against the reference in "
          r"Panels A and B (TF-IDF, LaBSE and multilingual-E5-large are not tested; for the reranker also P@1), and "
          r"citation accuracy, support, hallucination and legal correctness in Panel C; untested cells carry no "
          r"marker. Run-to-run SD of legal correctness over seeds 13, 42 and 2026 (RAG): " + sd_txt + r"~pp. "
          + NOTE + "}",
          r"\end{table}"]
    path.write_text("\n".join(L) + "\n", encoding="utf-8")


def write_data(t1, qtab, path):
    v = t1.set_index("item")["value"]
    q = qtab.set_index("type")
    left = [("Records in raw release", num(v["raw_records"]), "r"),
            ("Records removed", num(v["removed_total"]), "r"),
            ("Records after cleaning", num(v["clean_records"]), "r"),
            ("Acts selected / parsed", f"{num(v['acts_planned'])} / {num(v['acts_parsed'])}", "p/e"),
            (r"\textit{Chunks (median words)}", "", ""),
            ("\\quad Sentence-level", f"{num(v['sentence_chunks'])} ({v['sentence_median']:.0f})", "e"),
            ("\\quad Fixed-size, 200", f"{num(v['fixed_chunks'])} ({v['fixed_median']:.0f})", "e"),
            ("\\quad Sliding window, 200/100", f"{num(v['sliding_chunks'])} ({v['sliding_median']:.0f})", "e"),
            ("\\quad Structure-aware, $\\le$450", f"{num(v['sa_chunks'])} ({v['sa_median']:.0f})", "e")]
    right = [("Norm identification", f"{q.loc['norm', 'dev']} / {q.loc['norm', 'test']}", "p"),
             ("Interpretation", f"{q.loc['interp', 'dev']} / {q.loc['interp', 'test']}", "p"),
             ("Applicability conditions", f"{q.loc['applic', 'dev']} / {q.loc['applic', 'test']}", "p"),
             ("Procedural requirements", f"{q.loc['proc', 'dev']} / {q.loc['proc', 'test']}", "p"),
             ("Total", f"{q.loc['total', 'dev']} / {q.loc['total', 'test']}", "p"),
             ("Test with linked gold", f"{q.loc['total', 'test_with_gold']}", "e"),
             ("Test $n$ (retr. / gen.)", f"{q.loc['total', 'test_with_gold']} / {q.loc['total', 'test']}", "e/p"),
             ("", "", ""), ("", "", "")]
    L = ["% Table 1 (tab:data). Generated by src/make_compact_tables.py from outputs/data/table1_data.csv and",
         "% outputs/data/table1_questions.csv. Status r = reported in the data paper; p = planned; e = expected.",
         r"\begin{table}[tb]",
         r"\caption{Data used in the study. Status (St.): r, reported in the KazakhLawCorpus data paper "
         r"\citep{tleubayeva2026kazakhlawcorpus}; p, planned design value; e, expected value. Retrieval metrics use "
         r"the 381 test questions with linked gold evidence, generation metrics all 400. Values marked e are "
         r"expected values from a seeded simulation (not measured).}\label{tab:data}",
         r"\footnotesize", r"\setlength{\tabcolsep}{2pt}",
         r"\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}lrclrc@{}}", r"\toprule",
         r"Corpus, acts and chunks & Value & St. & Questions & Dev / test & St.\\", r"\midrule"]
    for (a, b, c), (d, e, f) in zip(left, right):
        L.append(f"{a} & {b} & {c} & {d} & {e} & {f}" + r"\\")
    L += [r"\botrule", r"\end{tabular*}", r"\end{table}"]
    path.write_text("\n".join(L) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="outputs/data")
    ap.add_argument("--out", default="outputs/tables")
    a = ap.parse_args()
    d, out = Path(a.data), Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    tests = pd.read_csv(d / "tests_all.csv")
    tests["significant"] = tests["significant"].astype(str).str.lower().eq("true")
    write_main(pd.read_csv(d / "table2_main.csv"), tests, pd.read_csv(d / "run_sd.csv"), out / "table_main.tex")
    write_data(pd.read_csv(d / "table1_data.csv"), pd.read_csv(d / "table1_questions.csv"), out / "table_data.tex")


if __name__ == "__main__":
    main()
