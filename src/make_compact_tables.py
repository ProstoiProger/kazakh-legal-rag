#!/usr/bin/env python3
"""Write the two compact LaTeX tables of the article from the CSV files of simulate.py.

    table_data.tex  Table 1 (tab:data): reported corpus counts and planned settings (no simulated values)
    table_main.tex  Table 2 (tab:main): main results, point values, bold best value per
                    panel column, dagger = Holm-significant difference from the panel's
                    reference configuration (taken from tests_all.csv)

All simulated values are EXPECTED values from a seeded simulation (not measured).

Usage (from the repository root, after the simulation):
    python src/make_compact_tables.py          # reads outputs/data, writes outputs/tables
"""
import argparse
from pathlib import Path

import pandas as pd

NOTE = "Expected values from a seeded simulation (not measured)."
RET_METRICS = ["R5", "R10", "MRR", "P1", "nDCG10"]
GEN_METRICS = ["em", "f1", "cit", "sup", "hal", "cor"]
MODELS = ["gpt", "kaz", "llama", "qwen"]
MODEL_NAMES = {"gpt": "GPT-6.1", "kaz": "KazLLM-1.0-8B", "llama": "Llama-3.1-8B", "qwen": "Qwen3.5-9B"}
PANEL_A = [("sentence", "Sentence-level"), ("fixed", "Fixed-size (200 words)"),
           ("sliding", "Sliding window (200/100)"), ("sa", "Structure-aware")]
PANEL_B = [("tfidf", "TF-IDF"), ("bm25", r"BM25$^{\mathrm{a}}$"), ("labse", "LaBSE"), ("e5", "multilingual-E5-large"),
           ("bge", "BGE-M3"), ("lin", r"Hybrid, linear ($\alpha=0.4$)"), ("rrf", r"Hybrid, RRF ($c=60$)"),
           ("rr", "Hybrid + reranker (dropped)")]
DROPPED = {"rr"}             # configurations dropped by a decision rule: shown, never bold
TYPE_SHORT = {"norm": "Norm identification", "interp": "Interpretation", "applic": "Applicability conditions",
              "proc": "Procedural requirements"}
# comparison in tests_all.csv -> configuration that carries the dagger
DAGGER_A = {"SA - Sentence": "sentence", "SA - Fixed": "fixed", "SA - Sliding": "sliding"}
DAGGER_B = {"Hybrid linear - BM25": "bm25", "Hybrid linear - BGE-M3": "bge",
            "RRF - linear": "rrf", "Reranker - none": "rr"}


def f1d(x):
    s = f"{x:.1f}"
    return "0.0" if s == "-0.0" else s


def num(x):
    return f"{int(round(x)):,}".replace(",", "{,}")


def daggers(tests):
    """Set of (config, metric) whose difference from the panel reference is significant."""
    out = set()
    for _, r in tests[tests["significant"]].iterrows():
        if r["family"] == "F1" and r["comparison"] in DAGGER_A:
            out.add((DAGGER_A[r["comparison"]], r["metric"]))
        elif r["family"] in ("F2", "F2s") and r["comparison"] in DAGGER_B:
            out.add((DAGGER_B[r["comparison"]], r["metric"]))
        elif r["family"] == "F3":
            m = [k for k, v in MODEL_NAMES.items() if r["comparison"].startswith(v + ":")][0]
            out.add((f"{m}_rag", r["metric"]))
    return out


def best(values, lower):
    vals = [round(v, 1) for v in values]
    return min(vals) if lower else max(vals)


def write_main(t2, tests, run_sd, path):
    dag = daggers(tests)

    def val(panel, c, m):
        return float(t2[(t2["panel"] == panel) & (t2["config"] == c) & (t2["metric"] == m)]["value"].iloc[0])

    def cell(v, is_best, is_sig, integer=False):
        s = f"{int(round(v))}" if integer else f1d(v)
        s = r"\textbf{" + s + "}" if is_best else s
        return s + (r"\s" if is_sig else "")

    L = ["% Table 2 (tab:main). Generated by src/make_compact_tables.py from outputs/data/table2_main.csv",
         "% and outputs/data/tests_all.csv. " + NOTE,
         r"\begin{table}[tb]",
         r"\caption{Main results on the test set. All metrics $\times 100$ (legal corr.: mean score of 0, 0.5 and 1; "
         r"definitions in Section~\ref{sec:metrics}); latency (Lat.) in ms per query. Bold: best value per panel column "
         r"among the configurations kept by the decision rules (lowest for hallucination and latency). $^{\dagger}$: "
         r"Holm-adjusted $p<0.05$ against structure-aware chunking (A), the linear hybrid (B) or the same model without "
         r"retrieval (C). $n=381$ (A, B; simulated count) and 400 (C). " + NOTE + r"}\label{tab:main}",
         r"\footnotesize", r"\setlength{\tabcolsep}{4pt}", r"\newcommand{\s}{$^{\dagger}$}",
         r"\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}llrrrrrr@{}}", r"\toprule"]
    for panel, rows, title in (
            ("A", PANEL_A, r"Panel A: chunking (hybrid, $\alpha=0.5$, no reranker); reference: structure-aware"),
            ("B", PANEL_B, r"Panel B: retrievers (structure-aware chunks); reference: linear hybrid")):
        L += [r"\multicolumn{8}{@{}l}{\textit{" + title + r"}}\\",
              r"\multicolumn{2}{@{}l}{Configuration} & R@5 & R@10 & MRR & P@1 & nDCG@10 & Lat.\\", r"\midrule"]
        kept = [c for c, _ in rows if c not in DROPPED]
        b = {m: best([val(panel, c, m) for c in kept], False) for m in RET_METRICS}
        b["lat"] = min(round(val(panel, c, "latency_ms")) for c in kept)
        for c, name in rows:
            k = c not in DROPPED
            cells = [cell(val(panel, c, m), k and round(val(panel, c, m), 1) == b[m], (c, m) in dag)
                     for m in RET_METRICS]
            lat = val(panel, c, "latency_ms")
            cells.append(cell(lat, k and round(lat) == b["lat"], False, integer=True))
            L.append(r"\multicolumn{2}{@{}l}{" + name + "} & " + " & ".join(cells) + r"\\")
        L.append(r"\midrule")
    L += [r"\multicolumn{8}{@{}l}{\textit{Panel C: generators (Kazakh system prompt); reference: same model, LLM-only}}\\",
          r"Model & Setting & EM & F1 & Cit.\ acc. & Support & Halluc. & Legal corr.\\", r"\midrule"]
    cfgs = [f"{m}_{s}" for m in MODELS for s in ("llm", "rag")]
    b = {m: best([val("C", c, m) for c in cfgs], m == "hal") for m in GEN_METRICS}
    for m in MODELS:
        for s, sname in (("llm", "LLM-only"), ("rag", "RAG")):
            c = f"{m}_{s}"
            cells = [cell(val("C", c, x), round(val("C", c, x), 1) == b[x], (c, x) in dag) for x in GEN_METRICS]
            L.append((MODEL_NAMES[m] if s == "llm" else "") + f" & {sname} & " + " & ".join(cells) + r"\\")
    sd = run_sd.drop_duplicates("model").set_index("model")["sd_pp"]
    sd_txt = ", ".join(f"{MODEL_NAMES[m]} {f1d(sd[MODEL_NAMES[m]])}" for m in MODELS)
    L += [r"\botrule", r"\end{tabular*}",
          r"\footnotetext{$^{\mathrm{a}}$With Kazakh stemming (planned). The reranker row is shown for completeness; "
          r"the reranker is dropped by the decision rule. Only planned comparisons are tested (R@10, MRR and nDCG@10 in "
          r"Panels A and B, except TF-IDF, LaBSE and multilingual-E5-large, plus P@1 for the reranker; citation accuracy, "
          r"support, hallucination and legal correctness in Panel C); untested cells carry no marker. All values are "
          r"assumed targets reproduced by a seeded simulation with a pre-specified significance pattern (not measured).}",
          r"\end{table}"]
    path.write_text("\n".join(L) + "\n", encoding="utf-8")


def write_data(qtab, path):
    """Table 1 contains no simulated values: reported data-paper counts and planned design values only."""
    q = qtab.set_index("type")
    r = "data paper"
    p_ = "planned"
    left = [("Period of adoption", "1947--2026", r),
            ("Records in raw release", num(223245), r),
            ("Records removed", num(7356), r),
            ("Records after cleaning", num(215889), r),
            ("Acts selected$^{\\mathrm{a}}$", num(1200), p_),
            (r"\textit{Chunking (planned settings)}", "", ""),
            (r"\quad Sentence-level", "1 sentence", p_),
            (r"\quad Fixed-size", "200 words", p_),
            (r"\quad Sliding window", "200, stride 100", p_),
            (r"\quad Structure-aware", r"$\le$450 words", p_)]
    right = [(TYPE_SHORT[t], str(q.loc[t, "dev"]), str(q.loc[t, "test"])) for t in ("norm", "interp", "applic", "proc")]
    right.append(("Total", str(q.loc["total", "dev"]), str(q.loc["total", "test"])))
    right += [("", "", "")] * (len(left) - len(right))
    L = ["% Table 1 (tab:data). Generated by src/make_compact_tables.py. No simulated values: counts reported in the",
         "% KazakhLawCorpus data paper and planned design values only (question counts from outputs/data/table1_questions.csv).",
         r"\begin{table}[tb]",
         r"\caption{Data and planned settings of the study. Source: data paper, reported in the KazakhLawCorpus data "
         r"paper \citep{tleubayeva2026kazakhlawcorpus}; planned, design value of the planned study. The question "
         r"split is stratified by type. The table contains no simulated values.}\label{tab:data}",
         r"\footnotesize", r"\setlength{\tabcolsep}{3pt}",
         r"\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}lrl@{\hspace{10pt}}lrr@{}}", r"\toprule",
         r"Corpus and settings & Value & Source & Questions (planned) & Dev & Test\\", r"\midrule"]
    for (a, b, c), (d, e, f) in zip(left, right):
        first = (r"\multicolumn{3}{@{}l}{" + a + "}") if not b else f"{a} & {b} & {c}"
        L.append(f"{first} & {d} & {e} & {f}" + r"\\")
    L += [r"\botrule", r"\end{tabular*}",
          r"\footnotetext{$^{\mathrm{a}}$All in-force acts referenced by the benchmark questions plus randomly "
          r"sampled in-force acts as distractors.}",
          r"\end{table}"]
    path.write_text("\n".join(L) + "\n", encoding="utf-8")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--data", default="outputs/data")
    ap.add_argument("--out", default="outputs/tables")
    a = ap.parse_args()
    d, out = Path(a.data), Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    tests = pd.read_csv(d / "tests_all.csv")
    tests["significant"] = tests["significant"].astype(str).str.lower().eq("true")
    write_main(pd.read_csv(d / "table2_main.csv"), tests, pd.read_csv(d / "run_sd.csv"), out / "table_main.tex")
    write_data(pd.read_csv(d / "table1_questions.csv"), out / "table_data.tex")


if __name__ == "__main__":
    main()
